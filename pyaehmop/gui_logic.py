"""Pure, testable configuration model used by the optional Tk desktop GUI.

This module deliberately does not import tkinter, matplotlib or solver code.
"""
from dataclasses import dataclass, field, fields
from pathlib import Path
import re


TASKS=("energy","charges","bands","dos","bonds","fmo","orbitals","matrices")
MODES=("eht","spin","soc","both")
FORMATS=("yaehmop","xyz","cif","ase")


@dataclass
class GuiSettings:
    structure_format:str="xyz"
    structure_file:str=""
    mode:str="eht"
    parameter_source:str="default"
    parameter_file:str=""
    calculations:tuple=field(default_factory=lambda:("energy","charges","dos"))
    output_dir:str=""
    workers:str="2"
    quadrature:str="24 20 12"
    cutoff:str="11"
    images:str="auto"
    kmesh:str=""
    kpoints:str=""
    k_shift:str=""
    band_path:str=""
    divisions:str="60"
    dos_sigma:str="0.15"
    dos_points:str="600"
    charge:str=""
    electrons:str=""
    weighted:str=""
    k:str=""
    bonds:str=""
    fragments:str=""
    ase_format:str=""
    frame:str=""
    plots:bool=True
    outputs:str="json,csv"
    initial_moment:str="2.5"
    mixing:str="0.3"
    temperature_ev:str="0.025"
    tolerance:str="0.00001"
    max_iter:str="140"
    spin_shell_parameters:str="stoner_fe_d = 0.88\nsoc_fe_d = 0.06"
    extra_options:str=""


EHT_OPTIONS=("charge","electrons","workers","quadrature","cutoff","images",
             "kmesh","kpoints","k_shift","band_path","divisions","dos_sigma",
             "dos_points","weighted","k","bonds","fragments",
             "ase_format","frame","outputs")
SPIN_OPTIONS=("charge","electrons","workers","quadrature","cutoff","images",
              "kmesh","band_path","divisions","dos_sigma","dos_points",
              "ase_format","initial_moment","mixing","temperature_ev",
              "tolerance","max_iter")
SKIP_EMPTY={"charge","electrons","kmesh","kpoints","k_shift","band_path",
            "bonds","fragments","ase_format","frame","weighted","k"}


def _pair_lines(raw,label):
    pairs=[]
    for number,line in enumerate(raw.splitlines(),1):
        line=line.strip()
        if not line or line.startswith(("#",";")):
            continue
        if "=" not in line:
            raise ValueError(f"{label} line {number}: expected key = value")
        key,val=line.split("=",1)
        key=key.strip().lower().replace("-","_")
        if not re.fullmatch(r"[a-z][a-z0-9_]*",key) or not val.strip():
            raise ValueError(f"{label} line {number}: invalid key or empty value")
        pairs.append((key,val.strip()))
    return pairs


def build_config(settings):
    """Return native .job/.spin text with all values selected in the GUI."""
    s=settings
    if s.structure_format not in FORMATS:
        raise ValueError("Choose YAeHMOP, XYZ, CIF or ASE as the structure format")
    if s.mode not in MODES:
        raise ValueError("Calculation mode must be EHT, spin, SOC or both")
    source=Path(s.structure_file).expanduser()
    if not source.is_file():
        raise FileNotFoundError(f"Structure file not found: {source}")
    if s.charge.strip() and s.electrons.strip():
        raise ValueError("Specify charge or electrons, not both")
    if s.parameter_source not in ("default","file","inline"):
        raise ValueError("Parameter source must be default, file or inline")
    if s.parameter_source=="file":
        parameter_file=Path(s.parameter_file).expanduser()
        if not parameter_file.is_file():
            raise FileNotFoundError(f"Parameter file not found: {parameter_file}")
        parameter=parameter_file.resolve().as_posix()
    elif s.parameter_source=="inline":
        parameter=s.parameter_file.strip()
        if not re.match(r"^[A-Za-z]{1,2}\s+\d+\s+",parameter):
            raise ValueError("Inline parameters must use a classic YAeHMOP record")
    else:
        parameter="default"
    if s.mode=="eht":
        selected=list(s.calculations)
        if not selected or not set(selected) <= set(TASKS)|{"all"}:
            raise ValueError("Select at least one valid calculation")
        if "all" in selected and len(selected)>1:
            raise ValueError("'all' cannot be combined with other calculations")
    outdir=Path(s.output_dir).expanduser().resolve() if s.output_dir.strip() else (
        Path.home()/"pyaehmop_gui_results").resolve()
    lines=["# Generated by PyYAeHMOP desktop GUI; scientific algorithms unchanged.",
           s.structure_format,source.resolve().as_posix(),"",
           "parameters = "+parameter]
    if s.mode=="eht":
        lines+=["calculations = "+", ".join(s.calculations)]
        names=EHT_OPTIONS
    else:
        spin=s.mode in ("spin","both")
        soc=s.mode in ("soc","both")
        lines+=[f"spin = {'yes' if spin else 'no'}",
                f"soc = {'yes' if soc else 'no'}"]
        names=SPIN_OPTIONS
    for key in names:
        value=str(getattr(s,key))
        if key in SKIP_EMPTY and not value.strip():
            continue
        # For spin, the existing engine generates bands only if a band_path
        # was requested, and always computes spin-DOS/SCF occupations.
        if key=="images" and s.structure_format=="xyz":
            continue
        if key=="divisions" and not s.band_path.strip() and not (
                s.mode=="eht" and ("bands" in s.calculations or "all" in s.calculations)):
            continue
        lines.append(f"{key} = {value.strip()}")
    lines.append("plots = "+("yes" if s.plots else "no"))
    if s.mode!="eht":
        allowed_prefix=("stoner_","soc_")
        entries=_pair_lines(s.spin_shell_parameters,"Spin/SOC shell parameters")
        keys={key for key,val in entries}
        if any(not key.startswith(allowed_prefix) for key in keys):
            raise ValueError("Spin/SOC shell entries must start with stoner_ or soc_")
        if spin and not any(k.startswith("stoner_") for k in keys):
            raise ValueError("Spin SCF requires at least one stoner_* parameter")
        if soc and not any(k.startswith("soc_") for k in keys):
            raise ValueError("SOC requires at least one soc_* parameter")
        lines +=[f"{key} = {val}" for key,val in entries]
    lines.append("output = "+outdir.as_posix())
    already=set()
    for line in lines:
        if "=" in line and not line.lstrip().startswith("#"):
            already.add(line.split("=",1)[0].strip())
    for key,value in _pair_lines(s.extra_options,"Advanced settings"):
        if key in already:
            raise ValueError(f"Duplicate setting: {key}")
        # Unlike a free-form eval, this only emits parsed key-value config.
        already.add(key)
        lines.append(f"{key} = {value}")
    return "\n".join(lines)+"\n"


def load_config(path):
    """Populate the GUI from an existing friendly .job or .spin file."""
    path=Path(path).expanduser().resolve()
    lines=[s.strip() for s in path.read_text(encoding="utf-8-sig").splitlines()
           if s.strip() and not s.lstrip().startswith(("#",";"))]
    if len(lines)<2:
        raise ValueError("Input requires a structure format and a file")
    fmt=lines[0].split("=",1)[-1].strip().lower()
    if fmt not in FORMATS:
        raise ValueError("Only friendly .job and .spin formats are supported by the GUI")
    source=lines[1].split("=",1)[-1].strip().strip("\"'")
    src=Path(source).expanduser()
    if not src.is_absolute():
        src=path.parent/src
    opts={}
    for key,val in _pair_lines("\n".join(lines[2:]),"Input"):
        if key in opts:
            raise ValueError(f"Duplicate setting {key}")
        opts[key]=val
    spin=opts.get("spin","no").lower() in ("yes","true","1")
    soc=opts.get("soc","no").lower() in ("yes","true","1")
    mode=("both" if spin and soc else "spin" if spin else "soc" if soc else "eht")
    if path.suffix.lower()==".spin" and mode=="eht":
        raise ValueError("A .spin file must enable spin, SOC or both")
    state=GuiSettings(structure_format=fmt,structure_file=str(src.resolve()),mode=mode)
    p=opts.pop("parameters","default")
    state.parameter_source=("default" if p.lower()=="default" else
                            "inline" if re.match(r"^[A-Za-z]{1,2}\s+\d+\s+",p)
                            else "file")
    if state.parameter_source=="inline":
        state.parameter_file=p
    if state.parameter_source=="file":
        fp=Path(p).expanduser()
        state.parameter_file=str((fp if fp.is_absolute() else path.parent/fp).resolve())
    if "calculations" in opts:
        state.calculations=tuple(t.strip() for t in opts.pop("calculations").split(",") if t.strip())
    else:
        state.calculations=("all",) if fmt=="yaehmop" else ("energy","charges")
    spin_options=[]
    for key in list(opts):
        if key.startswith(("stoner_","soc_")) and key!="soc":
            spin_options.append((key,opts.pop(key)))
    if spin_options:
        state.spin_shell_parameters="\n".join(f"{k} = {v}" for k,v in spin_options)
    opts.pop("spin",None);opts.pop("soc",None)
    valid={f.name for f in fields(GuiSettings)}
    extra=[]
    for key,val in opts.items():
        if key=="output":
            state.output_dir=str((Path(val) if Path(val).is_absolute()
                                   else path.parent/val).resolve())
        elif key=="plots":
            state.plots=val.lower() in ("yes","true","1","on")
        elif key in valid and key not in ("parameters","calculations"):
            setattr(state,key,val)
        else:
            extra.append(f"{key} = {val}")
    state.extra_options="\n".join(extra)
    return state


def render_config_to_file(state,output_folder):
    """Create a generated input file transparently, without manual editing."""
    folder=Path(output_folder).expanduser().resolve()
    folder.mkdir(parents=True,exist_ok=True)
    ext=".job" if state.mode=="eht" else ".spin"
    path=folder/("gui_calculation"+ext)
    path.write_text(build_config(state),encoding="utf-8")
    return path
